'use strict';
const assert = require('node:assert/strict');
const {
  expectedNote, validateTargetVdf, newestChangeNoteMatches, verifyWorkshopUpdate,
} = require('./steam_workshop_confirmation.cjs');
const id = '3838008670';
const sha = 'ae9b45062549e7813c8c84490912cdbf643bc039';
const version = '0.1.5';
const note = expectedNote(version, sha);
const vdf = `"workshopitem"\n{\n  "appid" "281990"\n  "publishedfileid" "${id}"\n  "contentfolder" "/some/mod"\n  "changenote" "${note}"\n}\n`;
const html = `<html><body><h1>Change Notes</h1><div>Showing 1-10 of 3 entries</div><div>Update: Nov 12 @ 1:37am</div><div>by Owner</div><div>${note}</div><div>Update: Nov 11 @ 1:37am</div><div>EPOCH 0.1.4 | commit 0000000000000000000000000000000000000000</div></body></html>`;
const older = `<html><div>Update: Nov 13 @ 1:37am</div><div>EPOCH 0.1.6 | commit 1111111111111111111111111111111111111111</div><div>Update: Nov 12 @ 1:37am</div><div>${note}</div></html>`;
const noMarkers = 'Steam Console Client\nLogging in using cached credentials\nUnloading Steam API...OK';
(async () => {
  assert.equal(validateTargetVdf(vdf, id, note), true);
  assert.equal(validateTargetVdf(vdf.replace(id,'9999999999'), id, note), false);
  assert.equal(validateTargetVdf(vdf.replace('281990','111'), id, note), false);
  assert.equal(validateTargetVdf(vdf.replace(note,'Wrong note'), id, note), false);
  assert.equal(newestChangeNoteMatches(html, note), true);
  assert.equal(newestChangeNoteMatches(older, note), false);
  assert.equal(newestChangeNoteMatches('<script>'+note+'</script><div>Update: Today</div>Wrong note', note), false);
  let calls = 0;
  const remote = async () => { calls++; return html; };
  const ok = await verifyWorkshopUpdate({ exitCode:0, output:noMarkers, workshopId:id, version, commit:sha, resultVdf:vdf, fetchPage:remote, attempts:1, delayMs:0 });
  assert.equal(ok.ok, true);
  assert.equal(ok.method, 'steam_changelog');
  assert.equal(calls,1);
  const failed = await verifyWorkshopUpdate({ exitCode:1, output:noMarkers, workshopId:id, version, commit:sha, resultVdf:vdf, fetchPage:remote, attempts:1, delayMs:0 });
  assert.equal(failed.ok, false);
  assert.equal(calls,1, 'No remote check on failed exit code');
  const badId = await verifyWorkshopUpdate({exitCode:0, output:noMarkers, workshopId:id,version,commit:sha,resultVdf:vdf.replace(id,'1234567890'),fetchPage:remote, attempts:1, delayMs:0 });
  assert.equal(badId.ok, false);
  assert.equal(calls,1);
  const err = await verifyWorkshopUpdate({exitCode:0,output:noMarkers+'\nERROR! Upload failed',workshopId:id,version,commit:sha,resultVdf:vdf,fetchPage:remote,attempts:1, delayMs:0});
  assert.equal(err.ok,false);
  assert.equal(calls,1, 'Reported Steam error must not be overridden');
  const prefixed = await verifyWorkshopUpdate({exitCode:0,output:noMarkers+'\n[Steam] ERROR! Failed to update workshop item',workshopId:id,version,commit:sha,resultVdf:vdf,fetchPage:remote,attempts:1,delayMs:0});
  assert.equal(prefixed.ok,false);
  assert.equal(calls,1, 'Prefixed Steam error must not be overridden');
  const wrongNewest = await verifyWorkshopUpdate({exitCode:0, output:noMarkers, workshopId:id,version,commit:sha,resultVdf:vdf,fetchPage:async()=>older,attempts:1,delayMs:0});
  assert.equal(wrongNewest.ok,false);
  const successOutput = 'Preparing update...\nPreparing content....\nUploading content....\nCommitting update...Success.Unloading Steam API...OK';
  const local = await verifyWorkshopUpdate({exitCode:0,output:successOutput,workshopId:id,version,commit:sha,resultVdf:vdf,fetchPage:async()=>{throw Error('remote should not be needed');},attempts:1,delayMs:0});
  assert.equal(local.ok,true);
  assert.equal(local.method,'steamcmd');
  console.log('PASS: remote latest commit proof, local upload commit, stale history, wrong target, explicit errors, and failed exit code.');
})().catch(err=>{console.error(err);process.exitCode=1;});
